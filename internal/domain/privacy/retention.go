package privacy

import (
	"context"
	"fmt"
	"time"

	"go.mongodb.org/mongo-driver/v2/bson"
)

// Retention limits (Ghana Data Protection Act 2012, s.24).
//
// Act 843 s.24 says personal data "shall not be kept for longer than is
// necessary" for the purpose it was collected for. There is no number in the
// statute, because the necessary period depends on the purpose — so the
// obligation is to have DECIDED a period per purpose and to actually enforce
// it, not to pick a figure that sounds prudent.
//
// # What is deliberately NOT here
//
// Nothing a church needs to run, and nothing anyone is required to keep:
//
//   - Giving, pledges and the ledger. Six years under the Revenue
//     Administration Act 2016 s.28, and the church's own accounts must
//     reconcile. These are handled by the deletion path instead, which
//     anonymises rather than removes.
//   - Members, attendance, events, the rota, sermons. A congregation's own
//     records, kept for as long as the church wants them. Deleting a member's
//     attendance because it turned three years old would be destroying the
//     church's history, not protecting anybody's privacy.
//   - Deletion receipts. They are the evidence a request was honoured, and
//     they hold no identity once purged.
//
// What IS here is operational exhaust: data generated BY the system rather
// than entered by the church, which serves a purpose that expires.
//
// # Why this is a sweeper and not a TTL index
//
// A Mongo TTL index would be simpler and is the obvious answer. It is rejected
// because it deletes silently and unconditionally: no log, no count, no way to
// answer "what did we remove last month" during an audit, and no chance to
// exclude a row that turns out to matter. For a compliance control, being able
// to show what it did is most of the value.

// RetentionRule is one category with a decided lifetime.
type RetentionRule struct {
	Collection string `json:"collection"`
	Label      string `json:"label"`
	// Field is the timestamp aged from.
	Field   string        `json:"field"`
	KeepFor time.Duration `json:"-"`
	// KeepForDays is the readable form, for the policy page.
	KeepForDays int `json:"keepForDays"`
	// Because states the purpose the period is derived FROM, which is what
	// s.24 actually asks a controller to be able to explain.
	Because string `json:"because"`
	// Only narrows the rule further — a status that means "finished".
	Only bson.M `json:"-"`
}

