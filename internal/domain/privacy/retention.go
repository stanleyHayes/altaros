// RetentionResult reports one enforcement pass.
type RetentionResult struct {
	// Removed counts per label, so a run can be reported rather than merely
	// having happened — see the note on why this is not a TTL index.
	Removed map[string]int64 `json:"removed"`
	Total   int64            `json:"total"`
}

// EnforceRetention removes data past its decided lifetime.
//
// Bounded per collection so a first run against years of backlog works through
// it over several passes rather than one that times out and deletes nothing.
func (s *Service) EnforceRetention(ctx context.Context) (*RetentionResult, error) {
	now := s.now()
	out := &RetentionResult{Removed: map[string]int64{}}

	for _, rule := range RetentionPolicy {
		cutoff := now.Add(-rule.KeepFor)

		filter := bson.M{rule.Field: bson.M{"$lt": cutoff}}
		for k, v := range rule.Only {
			filter[k] = v
		}

		res, err := s.db.Tenant(rule.Collection).DeleteMany(ctx, filter)
		if err != nil {
			// One category's failure must not stop the others: a malformed
			// document in the audit log should not mean stale push tokens are
			// kept for another year.
			continue
		}
		if res.DeletedCount > 0 {
			out.Removed[rule.Label] = res.DeletedCount
			out.Total += res.DeletedCount
		}
	}
	return out, nil
}

// RetentionDisclosure is the policy in the form a person can read.
//
// Act 843 s.32 gives a data subject the right to know how long their data is
// kept, not merely what is held — so this is part of the answer to a subject
// access request, and it is generated from the same rules the sweeper obeys.
func RetentionDisclosure() []RetentionRule {
	out := make([]RetentionRule, len(RetentionPolicy))
	copy(out, RetentionPolicy)
	return out
}

// String describes a rule for a log line.
func (r RetentionRule) String() string {
	return fmt.Sprintf("%s after %d days", r.Label, r.KeepForDays)
}
